const assert=require('node:assert/strict'),S=require('./connection-space.js');
const s=S.create('tripleMaze',{seed:'fold-view',dimensions:[[12,16],[24,16],[16,12]],floorUnderpasses:2});
const progress=S.tripleLoopProgress(s),sheet=S.groundSheet(s.world,s.id),layout=s.world.layouts[sheet];
s.x=100;s.y=-80;
const record={id:s.id,x:s.x+layout.width+2,y:s.y+1,wall:false,frame:[0,1,2,3]};
const chart={cells:new Map([['far',record]])};
assert.equal(S.foldedTripleMemory(s,chart).length,0);
progress.counts[sheet][0]=2;
assert.equal(S.foldedTripleMemory(s,chart).length,0,'two laps do not fold');
progress.counts[sheet][0]=3;
assert.deepEqual(S.foldedTripleMemory(s,chart).map(p=>[p.x,p.y]),[[2,1]]);
const before=JSON.stringify(s),remembered=JSON.stringify([...chart.cells]);
S.foldedTripleMemory(s,chart);
assert.equal(JSON.stringify(s),before,'render does not move or reorient player');
assert.equal(JSON.stringify([...chart.cells]),remembered,'render preserves source chart');
// After a quarter turn, world horizontal knowledge folds the screen vertical axis.
s.frame=[3,0,1,2];record.x=s.x+1;record.y=s.y+layout.width+2;
assert.deepEqual(S.foldedTripleMemory(s,chart).map(p=>[p.x,p.y]),[[1,2]]);
record.x=s.x+layout.height+1;record.y=s.y+2;
assert.equal(S.foldedTripleMemory(s,chart).length,0,'unknown world vertical stays unfolded');
progress.counts[sheet][1]=3;
assert.deepEqual(S.foldedTripleMemory(s,chart).map(p=>[p.x,p.y]),[[1,2]]);
const other=s.world.layouts[1].offset;
record.id=other;
assert.equal(S.foldedTripleMemory(s,chart).length,0,'other sheet never inherits current sheet periods');
record.id=-1;
assert.equal(S.foldedTripleMemory(s,chart).length,0,'unknown cells are not invented across periods');
record.id=s.id;record.frame=[2,1,0,3];record.wall=true;
assert.deepEqual(S.foldedTripleMemory(s,chart)[0].frame,record.frame,'remembered glyph orientation is retained');
assert.equal(S.foldedTripleMemory(s,chart)[0].wall,true);
console.log('Triple folding: threshold, rectangular periods, rotated axes, sheet isolation, memory and viewpoint retention passed.');
